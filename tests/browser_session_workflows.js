/* Real daemon/public API workflows. Only named HTTP failures/holds and catalog are fake. */
async (page, baseURL) => {
    const check = (ok, message) => { if (!ok) throw Error(message); };
    const context = await page.context().browser().newContext({ timezoneId: 'America/New_York' });
    await context.addInitScript(() => localStorage.setItem('timetrace_user_settings', JSON.stringify({idleDetectorEnabled:false})));
    const p = await context.newPage(), writes = [], dialogs = [], errors = [], results = [];
    p.on('request', r => { if (['POST','PUT','DELETE'].includes(r.method())) writes.push({ method:r.method(), path:new URL(r.url()).pathname, body:r.postData() }); });
    p.on('dialog', async d => { dialogs.push(d.message()); await d.dismiss(); });
    p.on('pageerror', e => errors.push(e.message));
    const request = async (method, path, data) => {
        const res = await context.request[method](`${baseURL}${path}`, data === undefined ? {} : { data });
        check(res.ok(), `${method} ${path}: ${res.status()} ${await res.text()}`);
        return res.status() === 204 ? null : res.json();
    };
    const readSession = id => request('get', `/sessions/${id}`);
    const visible = () => p.locator('#session_modal').waitFor({state:'visible'});
    const hidden = () => p.locator('#session_modal').waitFor({state:'hidden'});
    const save = () => p.locator('#session_modal_notes').press('Control+Enter');
    const task = await request('post','/api/tasks',{title:`Synthetic Session attachment ${Date.now()}`,tags:'#task',estimated_minutes:45});
    try {
        await p.goto(`${baseURL}/dashboard?date=2026-11-10&view=timeGridThreeDay`);
        await p.waitForSelector('.fc-timegrid-slot');
        await p.evaluate(() => openCreateSessionModal(new Date('2026-11-10T23:45:00'),new Date('2026-11-11T00:30:00')));
        await p.waitForFunction(() => document.activeElement.id === 'session_modal_task_search');
        await p.locator('#session_modal_task_search').fill(task.title);
        await p.locator('#session_modal_task_search').press('Enter');
        check(await p.locator('#session_modal_task_id').inputValue() === task.id,'Actual search Enter attaches chosen task');
        check(await p.evaluate(() => document.activeElement.id) === 'session_modal_tags_input','Attach immediately focuses Tags');
        await p.locator('#session_modal_tags_input').fill('#extra'); await p.keyboard.press('Enter');
        await p.locator('#session_modal_notes').fill('Retained\nNotes');
        const snapshot = await p.evaluate(() => [document.getElementById('session_modal_task_id').value,document.getElementById('session_modal_start').value,document.getElementById('session_modal_end').value,document.getElementById('session_modal_notes').value,[...currentTagChips]]);
        const metadata = '**/api/tasks?status=all';
        await p.route(metadata, route => route.fulfill({status:503,json:{detail:'Synthetic failed metadata'}}));
        await p.evaluate(() => taskKnowledge.changed());
        check(await p.locator('#task_metadata_notice').isVisible(),'Metadata failure exposes refresh-only retry');
        await p.unroute(metadata);
        await p.route(metadata, route => route.fulfill({json:[]}));
        await p.evaluate(() => taskKnowledge.refresh());
        check(JSON.stringify(await p.evaluate(() => [document.getElementById('session_modal_task_id').value,document.getElementById('session_modal_start').value,document.getElementById('session_modal_end').value,document.getElementById('session_modal_notes').value,[...currentTagChips]])) === JSON.stringify(snapshot),'Failed and empty metadata never detach or overwrite Session fields');
        await p.unroute(metadata); await p.evaluate(() => taskKnowledge.refresh());
        await save(); await hidden();
        let id = await p.locator('#edit_session_id').inputValue();
        let row = await readSession(id);
        check(row.task_id === task.id && row.notes === 'Retained\nNotes' && row.tags.includes('#extra'),'Real save readback retains attachment/tags/Notes');
        results.push({case:'search attach + failed/empty metadata + save',id,row});
        const eventLauncher = p.locator('.fc-event').filter({hasText:task.title}).first();
        await eventLauncher.click(); await visible();
        await p.waitForFunction(() => document.activeElement.id === 'session_modal_notes');
        await p.keyboard.press('Escape');
        check(await eventLauncher.evaluate(el=>document.activeElement===el),'Calendar event click restores actual event focus on Cancel');
        await eventLauncher.evaluate(el=>{window.sessionEventLauncher=el;});
        await eventLauncher.click(); await visible();
        await save(); await hidden();
        await p.waitForFunction(()=>!window.sessionEventLauncher.isConnected);
        check(await p.evaluate(()=>document.activeElement.id)==='calendar','Successful event Save restores stable Calendar region after launcher disposal');
        results.push({case:'actual mouse eventClick Cancel focus + Save disposed-launcher fallback'});

        await p.evaluate(id => openEditSessionModal(id),id); await visible();
        await p.getByRole('button',{name:'Detach task',exact:true}).click(); await save(); await hidden();
        check((await readSession(id)).task_id === null,'Only explicit detach clears saved relationship');
        await p.evaluate(id => openEditSessionModal(id),id); await visible();
        await p.locator('#session_modal_notes').fill('Nested retained\nNotes');
        const retained = await p.evaluate(() => [document.getElementById('session_modal_notes').value,document.getElementById('session_modal_start').value,document.getElementById('session_modal_end').value,[...currentTagChips]]);
        await p.locator('#session_modal_new_task_btn').click();
        check(await p.evaluate(() => document.activeElement.id) === 'modal_input_title','Nested Task immediately focuses title');
        await p.locator('#modal_input_title').fill('Canceled nested task'); await p.keyboard.press('Escape');
        await visible();
        check(await p.locator('#session_modal_task_id').inputValue() === '', 'Nested Cancel leaves detached Session draft');
        await p.locator('#session_modal_new_task_btn').click();
        const nestedTitle = `Synthetic nested task ${Date.now()}`;
        await p.locator('#modal_input_title').fill(nestedTitle);
        await p.locator('#task_modal button[onclick="saveTask()"] ').click();
        await visible();
        const nestedId = await p.locator('#session_modal_task_id').inputValue();
        check(nestedId && nestedId !== task.id,'Nested Task save attaches the returned task');
        check(JSON.stringify(await p.evaluate(() => [document.getElementById('session_modal_notes').value,document.getElementById('session_modal_start').value,document.getElementById('session_modal_end').value,[...currentTagChips]])) === JSON.stringify(retained),'Nested save resumes identical Session DOM fields');
        check((await readSession(id)).notes === 'Retained\nNotes','Task Save does not implicitly save Session');
        await save(); await hidden();
        row = await readSession(id);
        check(row.task_id === nestedId && row.notes === retained[0],'Explicit Session save persists nested attachment');
        results.push({case:'explicit detach + nested Cancel/create/attach + explicit Session Save',id,row});

        await p.evaluate(id => openEditSessionModal(id),id); await visible();
        await p.locator('#session_modal_notes').fill('Rejected then retried');
        await p.route(`**/sessions/${id}`, route => route.request().method() === 'PUT' ? route.fulfill({status:400,json:{detail:'Synthetic write rejection'}}) : route.continue());
        await save();
        await p.waitForFunction(() => !document.getElementById('session_modal_save_btn').disabled);
        check(await p.locator('#session_modal').isVisible() && (await readSession(id)).notes === row.notes,'Rejected mutation retains live draft and prior saved row');
        await p.unroute(`**/sessions/${id}`);
        await save(); await hidden();
        check((await readSession(id)).notes === 'Rejected then retried','Explicit retry persists previously rejected edit');
        results.push({case:'write rejection then explicit retry',dialogs:[...dialogs]});

        let release, started;
        const held = new Promise(r=>release=r), boundary = new Promise(r=>started=r);
        await p.route('**/sessions', async route => { if(route.request().method()==='POST'){started();await held;} await route.continue(); });
        await p.evaluate(() => openCreateSessionModal(new Date('2026-11-10T13:00:00'),new Date('2026-11-10T13:30:00')));
        await p.locator('#session_modal_notes').fill('Submitted once');
        const before = writes.filter(w=>w.path==='/sessions'&&w.method==='POST').length;
        await save(); await boundary;
        await save();
        await p.locator('#session_modal_notes').fill('Concurrent unsaved Notes');
        await p.locator('#session_modal_tags_input').fill('#concurrent'); await p.locator('#session_modal_tags_input').press('Enter');
        release();
        await p.waitForFunction(() => document.getElementById('session_modal_feedback').textContent.includes('New edits'));
        const concurrentId = await p.locator('#edit_session_id').inputValue();
        check(writes.filter(w=>w.path==='/sessions'&&w.method==='POST').length===before+1,'Pending double Ctrl+Enter sends one POST');
        check((await readSession(concurrentId)).notes==='Submitted once' && await p.locator('#session_modal_notes').inputValue()==='Concurrent unsaved Notes','Concurrent Notes remain unsaved in open dialog after successful write');
        check(await p.evaluate(()=>hasSettingsDrafts(['session_modal'])),'Concurrent Notes remain dirty after checkpoint');
        await p.locator('#session_modal_notes').fill('Submitted once');
        check(await p.evaluate(()=>hasSettingsDrafts(['session_modal'])),'Concurrent tags alone remain dirty after authoritative ID checkpoint');
        await p.locator('#session_modal_notes').fill('Concurrent unsaved Notes');
        await p.unroute('**/sessions');
        await save(); await hidden();
        check((await readSession(concurrentId)).notes==='Concurrent unsaved Notes','Second explicit save updates materialized create identity');
        results.push({case:'pending double activation + concurrent draft',id:concurrentId});

        const countBeforeTimer = (await request('get','/sessions')).length;
        await p.evaluate(() => {const now=new Date();openCreateSessionModal(new Date(now.getTime()-60000),new Date(now.getTime()+1800000));});
        await p.locator('#session_modal_notes').fill('Synthetic Timer Now\nNotes');
        await p.locator('#session_modal_start_now_btn').click(); await hidden();
        const status = await request('get','/timer/status');
        check(status.is_running && (await request('get','/sessions')).length===countBeforeTimer,'Start Timer Now starts file state without creating Session row');
        await request('post','/timer/stop',{});
        results.push({case:'Start Timer Now remains file state',status});
        check(errors.length===0,`No unexpected pageerrors: ${errors}`);
        return {results,writes,dialogs,errors,fakes:['metadata 503 then []','one rejected Session PUT','held real Session POST','catalog']};
    } finally {
        const timer = await context.request.get(`${baseURL}/timer/status`);
        if(timer.ok() && (await timer.json()).is_running) await context.request.post(`${baseURL}/timer/stop`,{data:{}});
        await context.close();
    }
}
